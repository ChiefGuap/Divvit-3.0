FIRST = ["Juniper", "Low Tide", "Copper Kettle", "Field Day", "Second Sun", "Paper Plane", "Little Wren", "North Arrow", "Saltbox",
         "Oak & Ember", "Tin Roof", "Marigold", "Quiet Hours", "Driftwood", "Lantern", "Sparrow & Stone", "Morning Glory", "Moss & Mill",
         "Westward", "Common Hours", "Half Moon", "Brass Owl", "Golden Hour", "Riverbend", "Clover", "Fig Tree", "Sunday Best",
         "Cinder", "Bramble", "Pinecone", "Tidewater", "Hollow Oak", "Kestrel", "Wildflower", "Ferris", "Corner Light", "Slow Loris",
         "Blue Heron", "Station Nine", "Two Birds", "Daybreak", "Lighthouse", "Teacup & Crow", "Mile Marker", "Open Sky", "Ironwood",
         "Plumtree", "Harbor Moth", "Quarter Past", "Gingham", "Starling", "Beacon Hill", "Small Batch", "Folk & Field", "Night Owl"]
LAST = ["Coffee", "Coffee Co.", "Espresso Bar", "Roasters", "Café", "Coffee House", "Coffee Bar"]
ALL_CATS = ["tech", "fintech", "health", "consumer", "food_bev", "climate", "education", "nonprofit", "local", "crypto"]

used = set()
rows = []
for city, (region, tier, hoods) in CITIES.items():
    for hood, (lat, lng) in hoods.items():
        for _ in range(random.randint(3, 5)):
            while True:
                name = f"{random.choice(FIRST)} {random.choice(LAST)}"
                if name not in used:
                    used.add(name); break
            cups = random.randrange(600, 3600, 50)
            sleeves = max(300, int(cups * 4.33 * random.uniform(0.25, 0.55)) // 50 * 50)
            r = random.random()
            accepted = [] if r < 0.6 else sorted(random.sample([c for c in ALL_CATS if c != "crypto"], random.randint(3, 6)))
            blocked = ["crypto"] if random.random() < 0.35 else []
            branded = random.random() < 0.75
            rows.append((name, hood, city, region, lat + random.uniform(-0.005, 0.005), lng + random.uniform(-0.006, 0.006),
                         tier, cups, sleeves, accepted, blocked, branded))

def arr(xs):
    return "'{" + ",".join(xs) + "}'"

def q(s):
    return "'" + s.replace("'", "''") + "'"

out = ["-- Sample café network for the marketplace. Generated by gen_demo_cafes.py — do not edit by hand.",
       "-- Every row is is_demo = true and has no owner, so no one can claim or edit it.",
       "delete from public.mp_cafes where is_demo;",
       "insert into public.mp_cafes (name, neighborhood, city, region, lat, lng, market_tier, weekly_cups, sleeves_per_month,",
       "  accepted_categories, blocked_categories, branded_drinks, is_demo) values"]
vals = []
for (name, hood, city, region, lat, lng, tier, cups, sleeves, acc, blk, br) in rows:
    vals.append(f"  ({q(name)}, {q(hood)}, {q(city)}, {q(region)}, {lat:.6f}, {lng:.6f}, {tier}, {cups}, {sleeves}, "
                f"{arr(acc)}, {arr(blk)}, {'true' if br else 'false'}, true)")
out.append(",\n".join(vals) + ";")
open("demo_cafes.sql", "w").write("\n".join(out) + "\n")
print(len(rows), "cafés")
